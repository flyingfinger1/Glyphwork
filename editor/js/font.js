const UNKNOWN = '#####|#...#|#...#|#...#|#...#|#...#|#####';

const cache = new Map();
function glyph(ch) {
  if (!cache.has(ch)) cache.set(ch, (G[ch] ?? UNKNOWN).split('|'));
  return cache.get(ch);
}

/** Advance in pixels, like the client: width + 1, space = 4. */
export function textWidth(s) {
  let w = 0;
  for (const ch of s) w += ch === ' ' ? 4 : glyph(ch)[0].length + 1;
  return w;
}

/** Draws text with its top-left pixel at (x, y) into pix (alpha-blended color). */
export function drawText(pix, s, x, y, argbColor) {
  for (const ch of s) {
    if (ch === ' ') { x += 4; continue; }
    const rows = glyph(ch);
    rows.forEach((row, ry) => [...row].forEach((c, rx) => { if (c === '#') blend(pix, x + rx, y + ry, argbColor); }));
    x += rows[0].length + 1;
  }
}

/** Source-over blend like the client's text shader (alpha < 0.1 is discarded). */
export function blend(pix, x, y, src) {
  if (!pix.inside(x, y)) return;
  const a = src >>> 24;
  if (a < 26) return;
  if (a === 255) { pix.set(x, y, src); return; }
  const dst = pix.get(x, y);
  const da = dst >>> 24;
  const oa = a + da * (255 - a) / 255;
  const mix = (sh) => {
    const sc = (src >>> sh) & 255, dc = (dst >>> sh) & 255;
    return oa === 0 ? 0 : Math.round((sc * a + dc * da * (255 - a) / 255) / oa);
  };
  pix.set(x, y, ((Math.round(oa) << 24) | (mix(16) << 16) | (mix(8) << 8) | mix(0)) >>> 0);
}

