package de.flyingfinger.glyphwork.font;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * Vanilla text glyphs (ascii, accented, nonlatin_european) re-registered with a shifted ascent,
 * so text can be placed at any pixel row (primitive P2 for text). Textures are not shipped,
 * the client already has them; only char grids and advances come from {@code vanilla_text.json}
 * (generated by tools/extract_vanilla_text.py).
 */
public final class VanillaText {

    private final JsonArray providers;
    private final JsonObject spaces;
    private final Map<Integer, Integer> advances = new HashMap<>();

    /**
     * Space with the width of ' ' that the client does not treat as a line-break opportunity.
     * Labels use it instead of ' ', so a GUI line can never wrap at a word boundary.
     */
    public static final char NB_SPACE = '';

    private VanillaText(JsonObject root) {
        this.providers = root.getAsJsonArray("providers");
        this.spaces = root.getAsJsonObject("spaces").deepCopy();
        this.spaces.addProperty(String.valueOf(NB_SPACE), this.spaces.get(" ").getAsInt());
        advances.put((int) NB_SPACE, this.spaces.get(" ").getAsInt());
        for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("advances").entrySet()) {
            advances.put(e.getKey().codePointAt(0), e.getValue().getAsInt());
        }
    }

    public static VanillaText load() {
        try (InputStream in = VanillaText.class.getResourceAsStream("/vanilla_text.json")) {
            if (in == null) {
                throw new IllegalStateException("vanilla_text.json missing");
            }
            return new VanillaText(JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject());
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Width in pixels as the client computes it (no bold). Unknown characters count as 6. */
    public int width(String text) {
        int w = 0;
        for (int i = 0; i < text.length(); ) {
            int cp = text.codePointAt(i);
            w += advances.getOrDefault(cp, 6);
            i += Character.charCount(cp);
        }
        return w;
    }

    /** Providers for a font whose glyphs are drawn {@code shift} pixels below the normal position. */
    public void addShiftedProviders(JsonArray target, int shift) {
        JsonObject space = new JsonObject();
        space.addProperty("type", "space");
        space.add("advances", spaces.deepCopy());
        target.add(space);
        for (JsonElement el : providers) {
            JsonObject p = el.getAsJsonObject();
            JsonObject copy = new JsonObject();
            copy.addProperty("type", "bitmap");
            copy.addProperty("file", p.get("file").getAsString());
            copy.addProperty("height", p.get("height").getAsInt());
            copy.addProperty("ascent", p.get("ascent").getAsInt() - shift);
            copy.add("chars", p.get("chars").deepCopy());
            target.add(copy);
        }
    }
}
